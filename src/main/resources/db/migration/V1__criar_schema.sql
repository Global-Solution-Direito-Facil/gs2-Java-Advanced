------------------------------------------------------------
-- TABELA: USUARIO (login do app: perfil CIDADAO ou GESTOR)
------------------------------------------------------------
CREATE TABLE T_DF_USUARIO (
    ID_USUARIO        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME              VARCHAR2(150)   NOT NULL,
    CPF               VARCHAR2(14)    NOT NULL,
    EMAIL             VARCHAR2(150)   NOT NULL,
    SENHA             VARCHAR2(255)   NOT NULL,
    PERFIL            VARCHAR2(10)    NOT NULL,
    DT_CADASTRO       DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT PK_DF_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_DF_USUARIO_CPF UNIQUE (CPF),
    CONSTRAINT UK_DF_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_DF_USUARIO_PERFIL CHECK (PERFIL IN ('CIDADAO', 'GESTOR'))
);

------------------------------------------------------------
-- TABELA: SALARIO_MINIMO (referencia dos criterios de renda)
------------------------------------------------------------
CREATE TABLE T_DF_SALARIO_MINIMO (
    ANO_REFERENCIA        NUMBER(4)      NOT NULL,
    VLR_SALARIO_MINIMO    NUMBER(8,2)    NOT NULL,
    DES_FONTE             VARCHAR2(200),

    CONSTRAINT PK_DF_SALARIO_MINIMO PRIMARY KEY (ANO_REFERENCIA),
    CONSTRAINT CK_DF_SM_VALOR CHECK (VLR_SALARIO_MINIMO > 0)
);

------------------------------------------------------------
-- TABELA: PESSOA (beneficiario acompanhado por um usuario responsavel)
------------------------------------------------------------
CREATE TABLE T_DF_PESSOA (
    ID_PESSOA             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO            NUMBER          NOT NULL,
    NOME                  VARCHAR2(150)   NOT NULL,
    DT_NASCIMENTO         DATE            NOT NULL,
    VLR_RENDA_FAMILIAR    NUMBER(10,2)    NOT NULL,
    QTD_MEMBROS_FAMILIA   NUMBER(3)       NOT NULL,
    DT_CADASTRO           DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT PK_DF_PESSOA PRIMARY KEY (ID_PESSOA),
    CONSTRAINT FK_DF_PESSOA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES T_DF_USUARIO(ID_USUARIO),
    CONSTRAINT CK_DF_PESSOA_RENDA CHECK (VLR_RENDA_FAMILIAR >= 0),
    CONSTRAINT CK_DF_PESSOA_MEMBROS CHECK (QTD_MEMBROS_FAMILIA > 0)
);

------------------------------------------------------------
-- TABELA: DOCUMENTO (registro, no banco do Java, de cada documento de laudo
-- anunciado pelo evento DocumentoRecebido). O arquivo e o banco da API .NET
-- sao independentes: aqui ficam so os metadados e a referencia externa
-- (DES_ID_EXTERNO = id do documento na API .NET, sem FK entre bancos).
-- DES_CHAVE_IDEMPOTENCIA e UNICA: se o RabbitMQ entregar o mesmo evento duas
-- vezes, o consumidor Java nao cria um segundo registro.
------------------------------------------------------------
CREATE TABLE T_DF_DOCUMENTO (
    ID_DOCUMENTO            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PESSOA               NUMBER          NOT NULL,
    DES_ID_EXTERNO          VARCHAR2(100)   NOT NULL,
    DES_NOME_ARQUIVO        VARCHAR2(200)   NOT NULL,
    DES_TIPO_MIDIA          VARCHAR2(50)    NOT NULL,
    NUM_TAMANHO_BYTES       NUMBER(12)      NOT NULL,
    DES_CHAVE_IDEMPOTENCIA  VARCHAR2(100)   NOT NULL,
    STATUS                  VARCHAR2(15) DEFAULT 'RECEBIDO' NOT NULL,
    DT_RECEBIMENTO          DATE DEFAULT SYSDATE NOT NULL,
    DT_PROCESSAMENTO        DATE,

    CONSTRAINT PK_DF_DOCUMENTO PRIMARY KEY (ID_DOCUMENTO),
    CONSTRAINT UK_DF_DOCUMENTO_EXT UNIQUE (DES_ID_EXTERNO),
    CONSTRAINT UK_DF_DOCUMENTO_IDEM UNIQUE (DES_CHAVE_IDEMPOTENCIA),
    CONSTRAINT FK_DF_DOCUMENTO_PESSOA FOREIGN KEY (ID_PESSOA) REFERENCES T_DF_PESSOA(ID_PESSOA),
    CONSTRAINT CK_DF_DOCUMENTO_STATUS CHECK (STATUS IN ('RECEBIDO', 'PROCESSADO', 'ERRO')),
    CONSTRAINT CK_DF_DOCUMENTO_TAM CHECK (NUM_TAMANHO_BYTES > 0)
);

------------------------------------------------------------
-- TABELA: LAUDO (dados estruturados extraidos do laudo; o texto bruto fica no MongoDB)
-- Regra: Lei 12.764/2012, art. 1o, par. 2o - TEA e considerado deficiencia (PcD).
------------------------------------------------------------
CREATE TABLE T_DF_LAUDO (
    ID_LAUDO          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PESSOA         NUMBER          NOT NULL,
    ID_DOCUMENTO      NUMBER,
    COD_CID           VARCHAR2(10)    NOT NULL,
    DES_CONDICAO      VARCHAR2(200)   NOT NULL,
    TIPO_CONDICAO     VARCHAR2(20)    NOT NULL,
    DT_LAUDO          DATE            NOT NULL,
    DT_CADASTRO       DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT PK_DF_LAUDO PRIMARY KEY (ID_LAUDO),
    CONSTRAINT FK_DF_LAUDO_PESSOA FOREIGN KEY (ID_PESSOA) REFERENCES T_DF_PESSOA(ID_PESSOA),
    CONSTRAINT FK_DF_LAUDO_DOCUMENTO FOREIGN KEY (ID_DOCUMENTO) REFERENCES T_DF_DOCUMENTO(ID_DOCUMENTO),
    CONSTRAINT CK_DF_LAUDO_TIPO CHECK (TIPO_CONDICAO IN
        ('TEA', 'DEF_FISICA', 'DEF_VISUAL', 'DEF_AUDITIVA', 'DEF_INTELECTUAL', 'DEF_MULTIPLA', 'OUTRA'))
);

------------------------------------------------------------
-- TABELA: DIREITO (catalogo de direitos federais)
------------------------------------------------------------
CREATE TABLE T_DF_DIREITO (
    ID_DIREITO         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    COD_DIREITO        VARCHAR2(40)    NOT NULL,
    NOME_DIREITO       VARCHAR2(150)   NOT NULL,
    DES_ORGAO          VARCHAR2(100)   NOT NULL,
    DES_BASE_LEGAL     VARCHAR2(200)   NOT NULL,
    GRUPO_ALVO         VARCHAR2(20)    NOT NULL,
    NUM_PRAZO_DIAS     NUMBER(4) DEFAULT 30 NOT NULL,
    STA_VERIFICACAO    VARCHAR2(10) DEFAULT 'CONFIRMAR' NOT NULL,

    CONSTRAINT PK_DF_DIREITO PRIMARY KEY (ID_DIREITO),
    CONSTRAINT UK_DF_DIREITO_COD UNIQUE (COD_DIREITO),
    CONSTRAINT CK_DF_DIREITO_GRUPO CHECK (GRUPO_ALVO IN ('AUTISMO', 'PCD', 'IDOSO', 'BAIXA_RENDA')),
    CONSTRAINT CK_DF_DIREITO_PRAZO CHECK (NUM_PRAZO_DIAS > 0),
    CONSTRAINT CK_DF_DIREITO_VERIF CHECK (STA_VERIFICACAO IN ('VERIFICADO', 'CONFIRMAR'))
);

------------------------------------------------------------
-- TABELA: CRITERIO_DIREITO (a REGRA fica em tabela, em fracoes do salario minimo)
------------------------------------------------------------
CREATE TABLE T_DF_CRITERIO_DIREITO (
    ID_CRITERIO       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_DIREITO        NUMBER          NOT NULL,
    NUM_IDADE_MIN     NUMBER(3) DEFAULT 0 NOT NULL,
    NUM_IDADE_MAX     NUMBER(3),
    STA_EXIGE_PCD     CHAR(1) DEFAULT 'N' NOT NULL,
    STA_EXIGE_TEA     CHAR(1) DEFAULT 'N' NOT NULL,
    FRC_SM_MAX        NUMBER(6,4),
    PCT_TOLERANCIA    NUMBER(5,2) DEFAULT 20 NOT NULL,

    CONSTRAINT PK_DF_CRITERIO PRIMARY KEY (ID_CRITERIO),
    CONSTRAINT UK_DF_CRITERIO_DIREITO UNIQUE (ID_DIREITO),
    CONSTRAINT FK_DF_CRITERIO_DIREITO FOREIGN KEY (ID_DIREITO) REFERENCES T_DF_DIREITO(ID_DIREITO),
    CONSTRAINT CK_DF_CRITERIO_PCD CHECK (STA_EXIGE_PCD IN ('S', 'N')),
    CONSTRAINT CK_DF_CRITERIO_TEA CHECK (STA_EXIGE_TEA IN ('S', 'N')),
    CONSTRAINT CK_DF_CRITERIO_FRC CHECK (FRC_SM_MAX IS NULL OR FRC_SM_MAX > 0),
    CONSTRAINT CK_DF_CRITERIO_TOL CHECK (PCT_TOLERANCIA BETWEEN 0 AND 100)
);

------------------------------------------------------------
-- TABELA: CASO (pedido de um direito, acompanhado ate a concessao)
------------------------------------------------------------
CREATE TABLE T_DF_CASO (
    ID_CASO              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PESSOA            NUMBER          NOT NULL,
    ID_DIREITO           NUMBER          NOT NULL,
    STATUS               VARCHAR2(25) DEFAULT 'ABERTO' NOT NULL,
    RESULTADO_AVALIACAO  VARCHAR2(15)    NOT NULL,
    DES_MOTIVO           VARCHAR2(300)   NOT NULL,
    DT_ABERTURA          DATE            NOT NULL,
    DT_PRAZO             DATE            NOT NULL,
    DT_ATUALIZACAO       DATE            NOT NULL,

    CONSTRAINT PK_DF_CASO PRIMARY KEY (ID_CASO),
    CONSTRAINT UK_DF_CASO_PESSOA_DIREITO UNIQUE (ID_PESSOA, ID_DIREITO),
    CONSTRAINT FK_DF_CASO_PESSOA FOREIGN KEY (ID_PESSOA) REFERENCES T_DF_PESSOA(ID_PESSOA),
    CONSTRAINT FK_DF_CASO_DIREITO FOREIGN KEY (ID_DIREITO) REFERENCES T_DF_DIREITO(ID_DIREITO),
    CONSTRAINT CK_DF_CASO_STATUS CHECK (STATUS IN
        ('ABERTO', 'EM_ANALISE', 'DOCUMENTOS_PENDENTES', 'PROTOCOLADO', 'CONCEDIDO', 'NEGADO')),
    CONSTRAINT CK_DF_CASO_RESULTADO CHECK (RESULTADO_AVALIACAO IN ('ELEGIVEL', 'POSSIVEL'))
);

------------------------------------------------------------
-- TABELA: ORIENTACAO (passo a passo em linguagem simples, gerado pela IA com
-- RAG e gravado pelo Java; o app mobile le pela API). 1:1 com o caso.
-- A fonte citada (lei ou cartilha oficial) e obrigatoria.
------------------------------------------------------------
CREATE TABLE T_DF_ORIENTACAO (
    ID_ORIENTACAO       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_CASO             NUMBER          NOT NULL,
    DES_PASSO_A_PASSO   VARCHAR2(4000)  NOT NULL,
    DES_FONTE           VARCHAR2(500)   NOT NULL,
    DES_MODELO          VARCHAR2(100),
    DT_GERACAO          DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT PK_DF_ORIENTACAO PRIMARY KEY (ID_ORIENTACAO),
    CONSTRAINT UK_DF_ORIENTACAO_CASO UNIQUE (ID_CASO),
    CONSTRAINT FK_DF_ORIENTACAO_CASO FOREIGN KEY (ID_CASO) REFERENCES T_DF_CASO(ID_CASO) ON DELETE CASCADE
);

------------------------------------------------------------
-- TABELA: AUDITORIA_CASO (trilha: data, operacao, valores antigo/novo)
-- Alimentada pelo gatilho TRG_DF_AUDITORIA_CASO
------------------------------------------------------------
CREATE TABLE T_DF_AUDITORIA_CASO (
    ID_AUDITORIA          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME_USUARIO          VARCHAR2(100)   NOT NULL,
    TIPO_OPERACAO         VARCHAR2(10)    NOT NULL,
    DATA_OPERACAO         DATE DEFAULT SYSDATE NOT NULL,
    ID_CASO_REF           NUMBER,
    STATUS_ANTERIOR       VARCHAR2(25),
    STATUS_NOVO           VARCHAR2(25),
    VALORES_ANTERIORES    VARCHAR2(1000),
    VALORES_NOVOS         VARCHAR2(1000),

    CONSTRAINT PK_DF_AUDITORIA_CASO PRIMARY KEY (ID_AUDITORIA),
    CONSTRAINT CK_DF_AUDIT_TIPO CHECK (TIPO_OPERACAO IN ('INSERT', 'UPDATE', 'DELETE'))
);

------------------------------------------------------------
-- TABELA: LOG_ERRO (toda procedure grava aqui quando cai em EXCEPTION)
------------------------------------------------------------
CREATE TABLE T_DF_LOG_ERRO (
    ID_LOG            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME_PROCEDURE    VARCHAR2(100)   NOT NULL,
    CODIGO_ERRO       NUMBER,
    MENSAGEM_ERRO     VARCHAR2(4000),
    DATA_ERRO         DATE DEFAULT SYSDATE NOT NULL,
    USUARIO_BANCO     VARCHAR2(100),

    CONSTRAINT PK_DF_LOG_ERRO PRIMARY KEY (ID_LOG)
);
